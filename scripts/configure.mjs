/** Generate static metadata and public browser settings. No dependencies. */
import { readFile, writeFile, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname, sep } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const settings = JSON.parse(
  await readFile(resolve(root, "site-settings.json"), "utf8"),
);
const url = new URL(settings.siteUrl);
if (
  url.protocol !== "https:" ||
  url.search ||
  url.hash ||
  url.username ||
  url.password ||
  url.pathname !== "/"
) {
  throw new Error(
    "siteUrl must be an HTTPS domain without a subdirectory, query or fragment.",
  );
}
const base = url.origin;
if (
  settings.lineUrl &&
  !/^https:\/\/(lin\.ee|line\.me)\//.test(settings.lineUrl)
) {
  throw new Error(
    "Use an official https://lin.ee/ or https://line.me/ LINE link.",
  );
}
if (
  settings.googleTagManagerId &&
  !/^GTM-[A-Z0-9]+$/.test(settings.googleTagManagerId)
) {
  throw new Error(
    "googleTagManagerId must be blank or a valid GTM- container ID.",
  );
}
const escape = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
let html = await readFile(resolve(root, "index.html"), "utf8");
html = html.replace(
  /<link\s+rel="canonical"\s+href="[^"]*"\s*\/?\s*>/g,
  `<link rel="canonical" href="${base}/">`,
);
html = html.replace(
  /<meta\s+property="og:url"\s+content="[^"]*"\s*\/?\s*>/g,
  `<meta property="og:url" content="${base}/">`,
);
html = html.replace(
  /<script type="application\/ld\+json">[\s\S]*?<\/script>/,
  `<script type="application/ld+json">\n${JSON.stringify(
    {
      "@context": "https://schema.org",
      "@type": "EducationalOrganization",
      name: "Arcko Creative & Design Academy",
      alternateName: "Arc Innovate",
      url: base + "/",
      logo: base + "/assets/images/arcko-logo-lockup.png",
      email: settings.email,
      telephone: settings.phone,
      description:
        "3D Printing, Tech Toy Design and Digital Arts for children ages 4–14 in Sathorn, Bangkok.",
      sameAs: [settings.instagramUrl, settings.lineUrl].filter(Boolean),
      hasMap: "https://maps.app.goo.gl/bFaTsB1kM1ziKFkr7",
      areaServed: { "@type": "City", name: "Bangkok" },
    },
    null,
    2,
  ).replaceAll("<", "\\u003c")}\n</script>`,
);
// These tags are regenerated; blank settings leave them absent rather than broken.
html = html.replace(
  /<meta\s+(?:name|property)="(?:google-site-verification|facebook-domain-verification|og:image(?::(?:width|height|alt))?|twitter:image)"[\s\S]*?>\s*/g,
  "",
);
const extra = [];
for (const [key, name] of [
  ["searchConsoleVerification", "google-site-verification"],
  ["metaDomainVerification", "facebook-domain-verification"],
]) {
  if (settings[key])
    extra.push(`<meta name="${name}" content="${escape(settings[key])}">`);
}
if (settings.socialImage) {
  const asset = resolve(root, settings.socialImage);
  if (!asset.startsWith(root + sep))
    throw new Error("socialImage must be a file inside the project.");
  await access(asset);
  const imageUrl = base + "/" + settings.socialImage.replace(/^\/+/, "");
  extra.push(
    `<meta property="og:image" content="${escape(imageUrl)}">`,
    `<meta property="og:image:alt" content="Arcko Creative & Design Academy">`,
    `<meta name="twitter:image" content="${escape(imageUrl)}">`,
  );
}
html = html.replace(
  /(<meta\s+name="twitter:card"\s+content=")[^"]+/,
  "$1" + (settings.socialImage ? "summary_large_image" : "summary"),
);
html = html.replace("</head>", extra.join("\n") + "\n</head>");
await writeFile(resolve(root, "index.html"), html);
await writeFile(
  resolve(root, "site-config.js"),
  "// Public settings generated by scripts/configure.mjs. Never put secrets here.\nwindow.ARCKO_CONFIG = Object.freeze(" +
    JSON.stringify(
      {
        email: settings.email,
        phone: settings.phone,
        lineUrl: settings.lineUrl,
        instagramUrl: settings.instagramUrl,
        googleTagManagerId: settings.googleTagManagerId,
      },
      null,
      2,
    ) +
    ");\n",
);
await writeFile(
  resolve(root, "robots.txt"),
  `User-agent: *\nAllow: /\nSitemap: ${base}/sitemap.xml\n`,
);
await writeFile(
  resolve(root, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${base}/</loc></url>\n</urlset>\n`,
);
console.log(
  "Updated canonical URL, schema, social metadata, sitemap and public settings for " +
    base,
);

// Keep article metadata and sitemap in sync with domain settings.
await import("./build-articles.mjs");
